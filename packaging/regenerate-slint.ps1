# Windows counterpart of regenerate-slint.sh, with relocatable asset includes.
param([string]$CargoPath = 'cargo')
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Push-Location $repo
try {
    & $CargoPath check -p udm-gui --features slint-compile --locked --offline
    if ($LASTEXITCODE -ne 0) { throw 'Slint compilation failed' }
    $generated = Get-ChildItem 'target\debug\build\udm-gui-*\out\app.rs' |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if (!$generated) { throw 'Generated app.rs not found' }
    $utf8 = [Text.UTF8Encoding]::new($false, $true)
    $source = [IO.File]::ReadAllText($generated.FullName, $utf8)
    $crate = (Join-Path $repo 'crates\gui').Replace('\', '\\') + '\\'
    $source = [regex]::Replace($source, 'include_bytes\s*!\s*\(\s*"([^"]+)"\s*\)', {
        param($match)
        $path = $match.Groups[1].Value
        if (!$path.StartsWith($crate, [StringComparison]::OrdinalIgnoreCase)) {
            throw "Asset outside GUI crate: $path"
        }
        $relative = $path.Substring($crate.Length).Replace('\\', '/')
        return 'include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/' + $relative + '"))'
    })
    [IO.File]::WriteAllText((Join-Path $repo 'crates\gui\src\slint_generated.rs'),
        "// Generated by Slint 1.18.1; regenerate with packaging/regenerate-slint.ps1.`n" + $source, $utf8)
    Write-Output 'Generated strict UTF-8 Rust with crate-relative embedded assets.'
} finally { Pop-Location }
