#[cfg(test)]
mod tests {
    use super::vi;
    use usagi::store::records::TaskState;

    #[test]
    fn every_engine_state_label_has_a_vietnamese_translation() {
        for state in [
            TaskState::Queued,
            TaskState::Probing,
            TaskState::Downloading,
            TaskState::Verifying,
            TaskState::Paused,
            TaskState::Completed,
            TaskState::Failed,
            TaskState::Canceled,
        ] {
            assert_ne!(
                vi(state.label()),
                state.label(),
                "untranslated state {state:?}"
            );
        }
    }

    #[test]
    fn unknown_text_and_user_paths_remain_verbatim() {
        for text in [
            "https://example.com/file?token=ABC",
            "D:\\Tải xuống\\My File.zip",
            "unrecognized diagnostic",
        ] {
            assert_eq!(vi(text), text);
        }
    }
}
